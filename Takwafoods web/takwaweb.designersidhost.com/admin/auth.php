<?php if ($setup): ?>
    <h1>Set a password</h1>
    <p class="sub">No password has been set for the applications inbox yet.
       Choose one now &mdash; this screen is only offered once.</p>
    <?php if ($error): ?><p class="err"><?= htmlspecialchars($error, ENT_QUOTES) ?></p><?php endif; ?>
    <label for="new_password">New password</label>
    <input type="password" id="new_password" name="new_password" required minlength="10" autofocus>
    <label for="confirm_password">Confirm</label>
    <input type="password" id="confirm_password" name="confirm_password" required minlength="10">
    <button type="submit">Set password</button>
    <p class="hint">At least 10 characters. Only a hash is stored, outside the
       web root. To reset it later, delete
       <code>takwa-admin-config.php</code> from the folder above public_html.</p>
<?php else: ?>
    <h1>Applications</h1>
    <p class="sub">Sign in to read the inbox.</p>
    <?php if ($error): ?><p class="err"><?= htmlspecialchars($error, ENT_QUOTES) ?></p><?php endif; ?>
    <?php if ($locked > 0 && !$error): ?>
        <p class="err">Locked for <?= (int) ceil($locked / 60) ?> more minutes.</p>
    <?php endif; ?>
    <label for="password">Password</label>
    <input type="password" id="password" name="password" required autofocus
           <?= $locked > 0 ? 'disabled' : '' ?>>
    <button type="submit" <?= $locked > 0 ? 'disabled' : '' ?>>Sign in</button>
<?php endif; ?>
</form>
</body>
</html>
<?php
exit;
